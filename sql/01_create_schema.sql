-- Star schema: 1 fact table + 5 dimension tables (dimensions are NOT linked to each other).
-- Safe to run many times (CREATE ... IF NOT EXISTS).
CREATE SCHEMA IF NOT EXISTS staging;   -- cleaned data exactly as produced by the Python scripts
CREATE SCHEMA IF NOT EXISTS dw;        -- the warehouse used by Power BI

CREATE TABLE IF NOT EXISTS dw.dim_date (
    date_key             INT PRIMARY KEY,          -- 20240315 = 15 March 2024; -1 = Unknown
    full_date            DATE,
    day_of_month         INT,
    day_name             TEXT,
    week_of_year         INT,
    month_num            INT,
    month_name           TEXT,
    year_month           TEXT,                     -- '2024-03', handy for monthly charts
    quarter              INT,
    year                 INT,
    is_weekend           BOOLEAN,
    is_ramadan           BOOLEAN,
    is_eid_ul_fitr       BOOLEAN,
    is_eid_ul_adha       BOOLEAN,
    is_independence_day  BOOLEAN,                  -- 14 August
    is_11_11             BOOLEAN,
    is_black_friday      BOOLEAN,
    is_holiday           BOOLEAN,                  -- Eid or 14 August
    event_name           TEXT
);

CREATE TABLE IF NOT EXISTS dw.dim_customer (
    customer_key      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,   -- -1 = Unknown
    customer_id       TEXT UNIQUE NOT NULL,        -- business key (the master ID after merging duplicates)
    full_name         TEXT,
    email             TEXT,
    phone             TEXT,
    gender            TEXT,
    registration_date DATE,
    birth_year        INT,
    age_group         TEXT,
    city              TEXT,
    province          TEXT,
    region            TEXT,
    first_order_date  DATE,
    customer_segment  TEXT                         -- RFM segment, filled after the fact table is built
);

CREATE TABLE IF NOT EXISTS dw.dim_product (
    product_key   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,       -- -1 = Unknown
    product_id    TEXT UNIQUE NOT NULL,
    product_name  TEXT,
    category      TEXT,
    sub_category  TEXT,
    brand         TEXT,
    list_price    NUMERIC(12,2),
    cost_price    NUMERIC(12,2),
    weight_kg     NUMERIC(8,2)
);

CREATE TABLE IF NOT EXISTS dw.dim_seller (
    seller_key   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,        -- -1 = Unknown
    seller_id    TEXT UNIQUE NOT NULL,
    seller_name  TEXT,
    join_date    DATE,
    seller_tier  TEXT,
    rating       NUMERIC(3,1),
    city         TEXT,
    province     TEXT,
    region       TEXT
);

CREATE TABLE IF NOT EXISTS dw.dim_location (
    location_key     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,    -- -1 = Unknown
    city_id          TEXT UNIQUE NOT NULL,
    city             TEXT,
    province         TEXT,
    region           TEXT,
    latitude         NUMERIC(9,4),
    longitude        NUMERIC(9,4),
    population_tier  TEXT
);

-- Grain: one row per order line item
CREATE TABLE IF NOT EXISTS dw.fact_sales (
    date_key         INT NOT NULL REFERENCES dw.dim_date(date_key),
    customer_key     INT NOT NULL REFERENCES dw.dim_customer(customer_key),
    product_key      INT NOT NULL REFERENCES dw.dim_product(product_key),
    seller_key       INT NOT NULL REFERENCES dw.dim_seller(seller_key),
    location_key     INT NOT NULL REFERENCES dw.dim_location(location_key),  -- city the order was shipped to
    order_id         TEXT NOT NULL,
    order_item_id    TEXT PRIMARY KEY,
    quantity         INT,
    unit_price       NUMERIC(12,2),
    gross_amount     NUMERIC(14,2),   -- quantity x unit price
    discount_amount  NUMERIC(14,2),
    net_amount       NUMERIC(14,2),   -- gross - discount
    cost_amount      NUMERIC(14,2),   -- cost_price x quantity
    shipping_fee     NUMERIC(12,2),   -- order fee split over its lines (adds back to the order fee)
    shipping_days    INT,
    is_cancelled     BOOLEAN,
    is_delivered     BOOLEAN,         -- not cancelled and not still In Transit
    is_returned      BOOLEAN,         -- has a valid (non-Rejected) return
    returned_amount  NUMERIC(14,2),
    return_date_key  INT REFERENCES dw.dim_date(date_key),
    return_reason    TEXT,
    return_status    TEXT,
    order_status     TEXT,
    payment_method   TEXT,
    channel          TEXT
);
CREATE INDEX IF NOT EXISTS ix_fact_order ON dw.fact_sales(order_id);

-- Pipeline bookkeeping (records read / rejected / loaded by each task)
CREATE TABLE IF NOT EXISTS dw.pipeline_log (
    run_at TIMESTAMP DEFAULT now(), task TEXT, detail TEXT,
    rows_read BIGINT, rows_rejected BIGINT, rows_loaded BIGINT
);
CREATE TABLE IF NOT EXISTS dw.reject_log (source_table TEXT, reject_reason TEXT, record TEXT);
CREATE TABLE IF NOT EXISTS dw.cleaning_log (script TEXT, step_table TEXT, step TEXT,
    rows_before TEXT, rows_after TEXT, changed_or_flagged TEXT, note TEXT);
